#!/usr/bin/env node
/**
 * Builds the deployable static web version into dist-web/.
 *
 *   node tools/build-web.mjs
 *
 * The output is a plain folder of files — no server, no build step at runtime,
 * no dependencies. Drop it on GitHub Pages / Netlify / Vercel / Cloudflare
 * Pages / any static host, or even open it from a USB stick over a local
 * server. In this mode the panel builds the Resolve Lua itself and hands it to
 * you to paste into Workspace ▸ Console.
 */
import { cp, copyFile, mkdir, readFile, readdir, rm, stat, writeFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'dist-web');

const PUBLIC_FILES = ['index.html', 'app.js', 'styles.css', 'touchdesigner.js', 'depth.js', 'audio-lab.js', 'asr.js', 'depth-live-worker.js', 'depth-ai-worker.js', 'render.js', 'lua-export.js'];

// The speech model (Whisper tiny, int8) and its runtime. 52 MB, shipped with the
// site so the transcription never leaves the machine and needs no API key.
const ASR_DIR = 'vendor/asr';

// The AI depth model + ONNX Runtime, copied verbatim. They are large (40 MB) and
// deliberately not part of PUBLIC_FILES: only the depth tab ever asks for them,
// and only when someone picks the AI engine.
const VENDOR_DIR = 'vendor/depth';
const VENDOR_FILES = [
  'ort.wasm.min.mjs',
  'ort-wasm-simd-threaded.mjs',
  'ort-wasm-simd-threaded.wasm',
  'depth-anything-v2-small-fp16.onnx',
  'NOTICE.md'
];

// index.html is shared with the local server build (absolute /paths). The web
// build only rewrites those, so both variants stay in sync from one source.
function rewriteHtml(html, stamp) {
  // The cache-buster matters: a browser holding yesterday's app.js shows a bug
  // that was fixed, and there is no way to tell from the page.
  const assets = '(styles\\.css|app\\.js|touchdesigner\\.js|depth\\.js|audio-lab\\.js|asr\\.js|render\\.js|lua-export\\.js)';
  return html
    .replace(new RegExp('(href|src)="\\/?' + assets + '(\\?v=[^"]*)?"', 'g'), '$1="$2?v=' + stamp + '"')
    .replace(/\/download\/bridge\.lua/g, 'VFXKit_ResolveFree_Bridge.lua')
    .replace(
      '<script src="touchdesigner.js"></script>',
      '<script src="web-config.js"></script>\n  <script src="touchdesigner.js"></script>'
    );
}

async function main() {
  // one stamp per build, taken from the newest source file
  const sources = await Promise.all(
    ['app.js', 'styles.css', 'index.html'].map((f) => stat(path.join(ROOT, 'public', f)).then((st) => st.mtimeMs))
  );
  const stamp = Math.round(Math.max(...sources)).toString(36);
  await rm(OUT, { recursive: true, force: true });
  await mkdir(OUT, { recursive: true });

  for (const file of PUBLIC_FILES) {
    if (file === 'index.html') continue;
    await cp(path.join(ROOT, 'public', file), path.join(OUT, file));
  }

  // vendored speech model + runtime (whole folder: weights, tokenizer, wasm)
  await cp(path.join(ROOT, 'public', ASR_DIR), path.join(OUT, ASR_DIR), { recursive: true });

  // vendored AI runtime + model
  await mkdir(path.join(OUT, VENDOR_DIR), { recursive: true });
  for (const file of VENDOR_FILES) {
    await cp(path.join(ROOT, 'public', VENDOR_DIR, file), path.join(OUT, VENDOR_DIR, file));
  }

  const html = await readFile(path.join(ROOT, 'public', 'index.html'), 'utf8');
  const rewritten = rewriteHtml(html, stamp);
  if (rewritten.includes('src="/')) {
    throw new Error('build-web: an absolute asset path survived the rewrite');
  }
  await writeFile(path.join(OUT, 'index.html'), rewritten, 'utf8');

  await writeFile(
    path.join(OUT, 'web-config.js'),
    "/* generated by tools/build-web.mjs — marks this folder as the static build */\n" +
      "window.PULSE_BUILD = 'web';\n",
    'utf8'
  );

  // the panel reads its native Fusion graphs from here (same file the bridge uses)
  // The same graph table the Node server serves, so the panel can build real
  // Fusion chains even when it is opened as plain files with no backend.
  await cp(path.join(ROOT, 'resolve-bridge', 'preset-recipes.json'), path.join(OUT, 'preset-recipes.json'));
  await cp(path.join(ROOT, 'resolve-bridge', 'preset-recipes.json'), path.join(ROOT, 'public', 'preset-recipes.json'));

  // so the "Download Bridge .lua" links keep working on the hosted site
  await cp(
    path.join(ROOT, 'resolve-bridge', 'VFXKit_ResolveFree_Bridge.lua'),
    path.join(OUT, 'VFXKit_ResolveFree_Bridge.lua')
  );

  // The Fusion macros, zipped, so the hosted page can hand them to anyone who
  // wants the native-effects route without cloning the repo.
  // Written into public/ so the local build serves it too, then copied out.
  const effectsZip = path.join(ROOT, 'public', 'PulseVFX-Effects.zip');
  try {
    await rm(effectsZip, { force: true });
    execFileSync('zip', ['-qr', effectsZip, '.', '-i', '*.setting'], { cwd: path.join(ROOT, 'fusion-macros') });
    await copyFile(effectsZip, path.join(OUT, 'PulseVFX-Effects.zip'));
    console.log('\n  PulseVFX-Effects.zip written (' + ((await stat(effectsZip)).size / 1024).toFixed(0) + ' KB)');
  } catch (err) {
    console.warn('\n  (skipped PulseVFX-Effects.zip: ' + (err && err.message) + ')');
  }

  // A ready-to-upload zip, so "deploy" can be: download one file, drag it onto
  // a host. Built with the system zip binary (present on macOS + CI images).
  const zipPath = path.join(ROOT, 'web-deploy.zip');
  try {
    await rm(zipPath, { force: true });
    execFileSync('zip', ['-qr', zipPath, '.'], { cwd: OUT });
    await cp(zipPath, path.join(OUT, 'web-deploy.zip'));
    console.log('\n  web-deploy.zip written (' + ((await stat(zipPath)).size / 1024).toFixed(0) + ' KB)');
  } catch (err) {
    console.warn('\n  (skipped web-deploy.zip: ' + (err && err.message) + ')');
  }

  const files = await readdir(OUT);
  let total = 0;
  const report = async (dir, prefix) => {
    for (const file of await readdir(dir)) {
      const full = path.join(dir, file);
      const info = await stat(full);
      if (info.isDirectory()) { await report(full, prefix + file + '/'); continue; }
      total += info.size;
      console.log('  ' + (info.size / 1024).toFixed(1).padStart(7) + ' KB  ' + prefix + file);
    }
  };
  await report(OUT, '');
  console.log('\ndist-web/ ready — ' + files.length + ' files, ' + (total / 1024 / 1024).toFixed(1) + ' MB');
  console.log('Serve it with any static host, e.g.  npx serve dist-web');
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
