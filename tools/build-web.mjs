#!/usr/bin/env node
/**
 * Builds the deployable static web version into dist-web/.
 *
 *   node tools/build-web.mjs
 *
 * The output is a plain folder of files — no server, no build step at runtime,
 * no dependencies. Drop it on GitHub Pages / Netlify / Vercel / Cloudflare
 * Pages / any static host, or even open it from a USB stick over a local
 * server. In this mode the panel builds the Resolve Lua itself and hands it to
 * you to paste into Workspace ▸ Console.
 */
import { cp, mkdir, readFile, readdir, rm, stat, writeFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'dist-web');

const PUBLIC_FILES = ['index.html', 'app.js', 'styles.css', 'touchdesigner.js', 'depth.js', 'lua-export.js'];

// index.html is shared with the local server build (absolute /paths). The web
// build only rewrites those, so both variants stay in sync from one source.
function rewriteHtml(html) {
  return html
    .replace(/(href|src)="\/(styles\.css|app\.js|touchdesigner\.js|depth\.js|lua-export\.js)"/g, '$1="$2"')
    .replace(/\/download\/bridge\.lua/g, 'VFXKit_ResolveFree_Bridge.lua')
    .replace(
      '<script src="touchdesigner.js"></script>',
      '<script src="web-config.js"></script>\n  <script src="lua-export.js"></script>\n  <script src="touchdesigner.js"></script>'
    );
}

async function main() {
  await rm(OUT, { recursive: true, force: true });
  await mkdir(OUT, { recursive: true });

  for (const file of PUBLIC_FILES) {
    if (file === 'index.html') continue;
    await cp(path.join(ROOT, 'public', file), path.join(OUT, file));
  }

  const html = await readFile(path.join(ROOT, 'public', 'index.html'), 'utf8');
  const rewritten = rewriteHtml(html);
  if (rewritten.includes('src="/')) {
    throw new Error('build-web: an absolute asset path survived the rewrite');
  }
  await writeFile(path.join(OUT, 'index.html'), rewritten, 'utf8');

  await writeFile(
    path.join(OUT, 'web-config.js'),
    "/* generated by tools/build-web.mjs — marks this folder as the static build */\n" +
      "window.PULSE_BUILD = 'web';\n",
    'utf8'
  );

  // the panel reads its native Fusion graphs from here (same file the bridge uses)
  await cp(path.join(ROOT, 'resolve-bridge', 'preset-recipes.json'), path.join(OUT, 'preset-recipes.json'));

  // so the "Download Bridge .lua" links keep working on the hosted site
  await cp(
    path.join(ROOT, 'resolve-bridge', 'VFXKit_ResolveFree_Bridge.lua'),
    path.join(OUT, 'VFXKit_ResolveFree_Bridge.lua')
  );

  // A ready-to-upload zip, so "deploy" can be: download one file, drag it onto
  // a host. Built with the system zip binary (present on macOS + CI images).
  const zipPath = path.join(ROOT, 'web-deploy.zip');
  try {
    await rm(zipPath, { force: true });
    execFileSync('zip', ['-qr', zipPath, '.'], { cwd: OUT });
    await cp(zipPath, path.join(OUT, 'web-deploy.zip'));
    console.log('\n  web-deploy.zip written (' + ((await stat(zipPath)).size / 1024).toFixed(0) + ' KB)');
  } catch (err) {
    console.warn('\n  (skipped web-deploy.zip: ' + (err && err.message) + ')');
  }

  const files = await readdir(OUT);
  let total = 0;
  for (const file of files) {
    const info = await stat(path.join(OUT, file));
    total += info.size;
    console.log('  ' + (info.size / 1024).toFixed(1).padStart(7) + ' KB  ' + file);
  }
  console.log('\ndist-web/ ready — ' + files.length + ' files, ' + (total / 1024 / 1024).toFixed(1) + ' MB');
  console.log('Serve it with any static host, e.g.  npx serve dist-web');
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
